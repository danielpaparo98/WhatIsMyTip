const siteUrl = useRuntimeConfig().public.siteUrl as string
const leagueName = computed(() => leagueConfig.value.displayName)

const homeMeta = computed(() => {
  if (isGrandFinalWeek.value && gfGame.value) {
    const matchup = `${displayName(gfGame.value.home_team)} vs ${displayName(gfGame.value.away_team)}`
    return {
      title: `${leagueName.value} Grand Final — ${matchup}`,
      description: `The ${leagueName.value} grand final decider: pre-match report, model predictions and tipping verdicts for ${matchup}.`,
    }
  }
  if (isSeasonComplete.value) {
    return {
      title: `${leagueName.value} ${seasonLabel.value ?? ''} Premier & Final Standings`,
      description: `The ${leagueName.value} season is complete — premier, final results and every graded tip of the season.`,
    }
  }
  return {
    title: `${leagueName.value} Tips & Fixtures`,
    description: `Every ${leagueName.value} game of the current round — fixtures, results and scores, updated automatically.`,
  }
})

useSeoMeta({
  title: () => homeMeta.value.title,
  description: () => homeMeta.value.description,
  ogTitle: () => homeMeta.value.title,
  ogDescription: () => homeMeta.value.description,
  twitterTitle: () => homeMeta.value.title,
  twitterDescription: () => homeMeta.value.description,
})

useHead({
  link: [
    { rel: 'canonical', href: () => `${siteUrl}/${leagueKey.value ?? ''}` },
  ],
})
</script>


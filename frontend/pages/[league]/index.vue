// ---------------------------------------------------------------------------
// GF adapters: the report/fallback sections consume the AFL prop shapes —
// `Tip` (selected_team) and `ModelPrediction` (non-null numbers). The
// league payload keys `picked` and allows abstaining models, so the
// derived heuristics map onto the AFL tip shape and null-winner models
// drop out (the same content the AFL sections would render).
// ---------------------------------------------------------------------------
const GF_DERIVED = new Set(['best_bet', 'weighted_tip', 'boosted_tip', 'yolo'])

const gfTips = computed<Tip[]>(() =>
  (gfDetail.value?.tips ?? [])
    .filter((t) => GF_DERIVED.has(t.heuristic))
    .map((t) => ({
      id: 0,
      game_id: 0,
      heuristic: t.heuristic,
      selected_team: t.picked ?? 'Draw',
      margin: t.margin ?? 0,
      confidence: t.confidence ?? 0,
      explanation: t.explanation ?? '',
      created_at: '',
    })),
)

const gfModels = computed<ModelPrediction[]>(() =>
  (gfDetail.value?.model_predictions ?? [])
    // m-3 (code review): the AFL ModelPrediction shape treats winner as
    // non-nullable — a malformed payload's undefined/empty winner drops
    // out instead of rendering as a pick.
    .filter((m): m is typeof m & { winner: string } => {
      const winner = m.winner
      return typeof winner === 'string' && winner.length > 0
    })
    .map((m) => ({
      model_name: m.model_name,
      winner: m.winner,
      confidence: m.confidence ?? 0,
      margin: m.margin ?? 0,
    })),
)

const gfAnalysis = computed(() => {
  const analysis = gfDetail.value?.match_analysis
  if (!analysis) return null
  return { ...analysis, game_id: analysis.event_id }
})

const modelDisplayName = (modelName: string): string =>
  leagueConfig.value.modelDisplayNames[modelName] ??
  modelName.replaceAll('_', ' ')

// Round strip: 'GF • {season}' for the final round (upcoming or done),
// 'R{n} • {season}' for every regular round.
const roundStrip = computed(() => {
  if (roundId.value === null) return ''
  const season = seasonLabel.value ?? ''
  return seasonState.value === 'regular'
    ? `R${roundId.value} • ${season}`
    : `GF • ${season}`
})

// Premier for the celebration: winner of the latest-dated completed event.
const premier = computed(() => derivePremier(seasonEvents.value))

// OffSeasonCelebration renders the season as a number (AFL contract);
// the league season label is the same four-digit year as a string.
const seasonNumber = computed<number | null>(() => {
  const parsed = Number.parseInt(seasonLabel.value ?? '', 10)
  return Number.isFinite(parsed) ? parsed : null
})

// Confetti palette: both finalists' club colours from the curated
// league palettes (primary + secondary per club). Null when no palette
// resolves — ConfettiEffect then falls back to its celebratory default.
const confettiColors = computed<string[] | null>(() => {
  const league = leagueKey.value
  if (!league) return null
  const colors: string[] = []
  for (const ev of roundEvents.value) {
    for (const p of ev.participants) {
      const club = leagueColorFor(league, p.participant_name)
      if (club && !colors.includes(club.primary)) {
        colors.push(club.primary, club.secondary)
      }
    }
  }
  return colors.length > 0 ? colors : null
})


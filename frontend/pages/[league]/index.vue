const sideOf = (ev: SportEvent, side: string) =>
  ev.participants.find((p) => p.side === side)
const sideName = (ev: SportEvent, side: string): string =>
  sideOf(ev, side)?.participant_name ?? 'TBD'
const sideScore = (ev: SportEvent, side: string): number | null =>
  sideOf(ev, side)?.score ?? null
const sideIsWinner = (ev: SportEvent, side: string): boolean =>
  sideOf(ev, side)?.is_winner === true

const seasonState = computed(() => deriveSeasonState(seasonEvents.value, roundId.value))
const isSeasonComplete = computed(() => seasonState.value === 'season_complete')

// ---------------------------------------------------------------------------
// PARITY (2026-10-14): GRAND-FINAL WEEK — the AFL home's STATE 1. The
// displayed round is the season's highest round and still has live
// fixtures: the decider (the round's first live event with both sides)
// gets the SAME treatment the AFL home gives its grand final — the
// stored GF report via GrandFinalReport, or the standard detail
// experience until the nightly sweep writes it.
// ---------------------------------------------------------------------------
const isGrandFinalWeek = computed(() => seasonState.value === 'grand_final_upcoming')

const grandFinalEvent = computed<SportEvent | null>(() => {
  if (!isGrandFinalWeek.value) return null
  const finalRound = roundId.value
  const candidates = roundEvents.value.filter(
    (ev) =>
      ev.round_id === finalRound &&
      !ev.completed &&
      sideOf(ev, 'home') !== undefined &&
      sideOf(ev, 'away') !== undefined,
  )
  return candidates[0] ?? null
})

const {
  data: gfData,
  pending: gfPending,
  refresh: refreshGrandFinal,
} = await useAsyncData(
  computed(
    () => `league-gf-${leagueKey.value ?? 'x'}-${grandFinalEvent.value?.slug ?? 'none'}`,

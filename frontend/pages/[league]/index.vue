onMounted(() => {
  const stored = localStorage.getItem('selected-heuristic')
  const legal = heuristicOptions.value.some((h) => h.value === stored)
  if (stored && legal && stored !== selectedHeuristic.value) {
    selectedHeuristic.value = stored
  }

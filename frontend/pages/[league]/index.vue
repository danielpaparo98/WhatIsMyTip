// refetch rides the tick, so the "poller adopts it automatically"
// contract in the GF fallback template is real.
// ---------------------------------------------------------------------------
const AUTO_REFRESH_MS = 5 * 60 * 1000

let autoRefreshTimer: ReturnType<typeof setInterval> | null = null

onMounted(() => {
  // Post-build GF freshness: the fixtures/tips composables self-refresh
  // via their own onNuxtReady hooks; the GF payload has no self-refresh,
  // so the report (generated by the nightly sweep, possibly after this
  // page was prerendered) is adopted here (M-2, code review).
  if (isGrandFinalWeek.value) void refreshGrandFinal()

  autoRefreshTimer = setInterval(() => {
    if (document.visibilityState !== 'visible') return
    void refresh()
    void refreshTips()
    if (isGrandFinalWeek.value) void refreshGrandFinal()
  }, AUTO_REFRESH_MS)
})

onUnmounted(() => {
  if (autoRefreshTimer !== null) clearInterval(autoRefreshTimer)
})

// ---------------------------------------------------------------------------

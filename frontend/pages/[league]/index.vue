    // 404 on the report means "not generated yet" (mapped to null inside
    // getEventReport, AFL parity); ANY failure degrades to null — the
    // standard detail experience must never break the page.
    const detail = await api.getEventDetail(ev.slug).catch(() => null)
    const report = await api.getEventReport(ev.slug).catch(() => null)
    return { detail, report }
  },
  { dedupe: 'cancel' },
)

const gfDetail = computed(() => gfData.value?.detail ?? null)
const gfReport = computed(() => gfData.value?.report ?? null)

/** The report component's header shape (structural AFL `Game` twin). */

/**
 * The card's tip for an upcoming fixture under the SELECTED heuristic —
 * the AFL card shape (FCL-14 + PARITY): the stored pick's side name,
 * confidence (0..1), margin (points) and persisted AI explanation.
 * Null when no stored tip exists for that heuristic — the card shows
 * the AFL's "No tip available" state.
 */
const pickFor = (
  ev: SportEvent,
): {
  name: string
  confidence: number | null
  margin: number | null
  explanation: string | null
} | null => {
  const pick = tipsBySlug.value[ev.slug]?.[selectedHeuristic.value]
  if (!pick || pick.picked === undefined) return null
  return {
    name: pick.picked === null ? 'Draw' : pick.picked,
    confidence: pick.confidence ?? null,
    margin: pick.margin ?? null,
    explanation: pick.explanation ?? null,
  }
}

// PARITY: em-dash → en-dash normalisation, the AFL home's exact
// formatExplanation treatment (clamped via CSS).
const formatExplanation = (text: string): string => text.replace(/—/g, '–')

// Per-league presentation config resolved from the ROUTE (not the
// global activeConfig): the prerender bakes every league page in one

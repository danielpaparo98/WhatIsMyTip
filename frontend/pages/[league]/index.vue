// ---------------------------------------------------------------------------
// PARITY (2026-10-14): the AFL home's auto-refresh poller, mirrored —
// every 5 minutes (visible tab only) the round's fixtures, stored tips
// AND the grand-final report re-fetch, so a page left open through the
// nightly sweep adopts the report without a reload.
